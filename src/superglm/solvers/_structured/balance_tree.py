# IEEE binary64 unit roundoff (Higham 2002, section 2.1) and gamma_n (section 3.1).
_UNIT = 2.0**-53
_EPS = float(np.finfo(np.float64).eps)
# Block-factor note §4.3: a pivot direction whose scaled pivot squared is below
# 20 k eps is deferred to the border (cost only).
_DEFERRAL_FACTOR = 20.0


def _gamma(count: float) -> float:
    return count * _UNIT / (1.0 - count * _UNIT)


def _gamma_array(count: NDArray) -> NDArray:
    return count * _UNIT / (1.0 - count * _UNIT)


def _append_generators(
    generators: BorderGenerators | None, extra: NDArray, term_name: str
) -> BorderGenerators:
    """``generators`` (rest coordinates) with the columns of ``extra``, reduced to ``N[refs] = I``.

    Gauss-Jordan in a fixed order (as ``border.reduce_generators``): each
    extra column is cleared on the references already chosen, takes as its
    reference its largest entry (lowest index on ties) and clears that
    reference in every earlier generator; a column that clears to its
    rounding is dependent and dropped.  The span is unchanged, so the
    deflation (border step 1) is too.  Deterministic.
    """
    width = extra.shape[0]
    columns: list[NDArray] = []
    references: list[int] = []
    labels: list[str] = []
    if generators is not None:
        columns = [np.array(column, dtype=np.float64) for column in generators.matrix.T]
        references = [int(reference) for reference in generators.references]
        labels = list(generators.labels) + [""] * (len(columns) - len(generators.labels))
    for index in range(extra.shape[1]):
        vector = np.array(extra[:, index], dtype=np.float64)
        size = float(np.max(np.abs(vector), initial=0.0))
        for column, reference in zip(columns, references, strict=True):
            if vector[reference] != 0.0:
                vector -= vector[reference] * column
        largest = float(np.max(np.abs(vector), initial=0.0))
        if not largest > width * _EPS * size:
            continue
        reference = int(np.argmax(np.abs(vector)))
        vector = vector / vector[reference]
        vector[reference] = 1.0
        for position, column in enumerate(columns):
            if column[reference] != 0.0:
                column = column - column[reference] * vector
                column[reference] = 0.0
                columns[position] = column
        columns.append(vector)
        references.append(reference)
        labels.append(f"{term_name}: a thin level's penalized alias")
    matrix = np.column_stack(columns) if columns else np.zeros((width, 0))
    return BorderGenerators(matrix, np.array(references, dtype=np.intp), tuple(labels))


# ------------------------------------------------------------- topology ----
@dataclass(frozen=True, eq=False)
class BalanceTree:
    """A balanced binary partition of ``K`` levels (internal nodes in post-order).

    ``child[v] = (left, right)``: an internal node id ``>= 0`` or a leaf ``-(l +
    1)``; ``h[v]`` the balance multipliers of the two halves; ``parent[v]``
    (``-1`` at the root, the last id); ``lo``/``hi`` the level range of a node;
    ``depth`` the number of merges on the longest root-to-leaf path.
    """

    n_levels: int
    child: NDArray
    h: NDArray
    parent: NDArray
    lo: NDArray
    hi: NDArray
    depth: int

    @property
    def n_internal(self) -> int:
        return int(self.child.shape[0])


@lru_cache(maxsize=16)
def balance_tree(n_levels: int) -> BalanceTree:
    """The balance tree of ``n_levels >= 2`` levels in code order (left half ``ceil(n / 2)``)."""
    if n_levels < 2:
        raise ValueError("A balance tree needs at least two levels.")
    child: list[tuple[int, int]] = []
    hs: list[tuple[float, float]] = []
    los: list[int] = []
    his: list[int] = []

    def build(lo: int, hi: int) -> int:
        n = hi - lo
        if n == 1:
            return -(lo + 1)
        n_left = (n + 1) // 2
        left = build(lo, lo + n_left)
        right = build(lo + n_left, hi)
        n_right = n - n_left
        child.append((left, right))
        hs.append((math.sqrt(n_right / (n_left * n)), -math.sqrt(n_left / (n_right * n))))
        los.append(lo)
        his.append(hi)
        return len(child) - 1

    build(0, n_levels)
    child_array = np.array(child, dtype=np.int64)
    parent = np.full(len(child), -1, dtype=np.int64)
    leaf_parent = np.empty(n_levels, dtype=np.int64)
    for node, pair in enumerate(child):
        for value in pair:
            if value >= 0:
                parent[value] = node
            else:
                leaf_parent[-value - 1] = node
    depth = 0
    for level in range(n_levels):
        steps, node = 0, int(leaf_parent[level])
        while node >= 0:
            steps += 1
            node = int(parent[node])
        depth = max(depth, steps)
    arrays = [
        child_array,
        np.array(hs, dtype=np.float64),
        parent,
        np.array(los, dtype=np.int64),
        np.array(his, dtype=np.int64),
    ]
    for array in arrays:
        array.setflags(write=False)
    return BalanceTree(n_levels, *arrays, depth=depth)


