@dataclass(frozen=True, eq=False)
class _LevelForm:
    """A symmetric operator in level space: ``D`` ``(K, k, k)`` per level, ``Cx`` ``(K, k, n_x)``
    level-to-border coupling, ``Ax`` ``(n_x, n_x)``, plus ``sum U_t R_t U_t'`` with level parts
    ``Ul`` ``(K, k, r)`` and border parts ``Ux`` ``(n_x, r)`` (``x = [alpha | carried | border]``)."""

    D: NDArray
    Cx: NDArray
    Ax: NDArray
    low: tuple = ()

    def __add__(self, other: _LevelForm) -> _LevelForm:
        return _LevelForm(
            self.D + other.D, self.Cx + other.Cx, self.Ax + other.Ax, self.low + other.low
        )

    def apply(self, Ul: NDArray, Ux: NDArray) -> tuple[NDArray, NDArray]:
        """``O u`` for level/border vectors ``(K, k, m)``, ``(n_x, m)``."""
        out_l = np.einsum("lij,ljm->lim", self.D, Ul) + np.einsum("lie,em->lim", self.Cx, Ux)
        out_x = np.einsum("lie,lim->em", self.Cx, Ul) + self.Ax @ Ux
        for low_l, low_x, core in self.low:
            coefficients = core @ (np.einsum("lir,lim->rm", low_l, Ul) + low_x.T @ Ux)
            out_l = out_l + np.einsum("lir,rm->lim", low_l, coefficients)
            out_x = out_x + low_x @ coefficients
        return out_l, out_x


class SumToZeroTreeFactor:
    """Factorization of an ``sz`` system in augmented coordinates ``[1, X]`` (module docstring).

    The public attributes and methods follow ``FactorSmoothLeafFactor``:
    ``shape``, ``small_indices`` (intercept 0 first), ``structured_indices``
    ``(K - 1, k)`` (public levels), ``n_levels`` (all ``K``), ``rank``,
    ``rank_truncated``, ``logdet``, ``solve``, ``solve_data``, the selected
    inverses, every trace, ``raw_level_inverse_block`` (the covariance of any
    level, the last one included), ``border_certificate``,
    ``weakly_identified_coefficients`` and ``thin_levels``.  ``excluded``
    border columns (augmented global indices) are left out of the Laplace term
    as the fs factor leaves them.  ``deferred`` counts the carried coordinates.
    """

    backend = "structured"

    def __init__(
        self,
        system: SumToZeroLeafSystem,
        penalized: SumToZeroPenalizedOperator,
        *,
        max_structured_inverse_block: int = 256,
        excluded: tuple[int, ...] = (),
    ):
        with narrow_kernel_blas_threads(system.leaf.width + 1):
            self._construct(system, penalized, int(max_structured_inverse_block), excluded)

    # -- construction ---------------------------------------------------------
    def _construct(self, system, penalized, max_block: int, excluded) -> None:
        from superglm.solvers._structured.block_leaves import _penalty_roots

        leaf = system.leaf
        operator = system.operator
        if penalized.penalty_local is None or penalized.penalty_small is None:
            raise ValueError("An sz factor needs the penalized operator's penalty parts.")
        self.system = system
        self.penalized = penalized
        self.term_name = self.dominant_group_name = system.dominant_group_name
        self.max_structured_inverse_block = max_block
        K, k = operator.n_levels, operator.block_size
        q = len(operator.small_indices)
        self.n_levels, self.block_size = K, k
        self.small_indices = np.concatenate(([0], operator.small_indices + 1)).astype(np.intp)
        self.structured_indices = (operator.structured_indices + 1).astype(np.intp)
        size = operator.shape[0] + 1
        self.shape = (size, size)
        self._small_position = np.full(size, -1, dtype=np.intp)
        self._small_position[self.small_indices] = np.arange(q + 1)
        self._structured_position = np.full(size, -1, dtype=np.intp)
        self._structured_position[self.structured_indices.ravel()] = np.arange((K - 1) * k)
        self._center = np.asarray(leaf.center, dtype=np.float64)
        self.thin_levels = tuple(getattr(system, "thin_levels", ()))
        tree = balance_tree(K)
        self._tree = tree
        n_int = tree.n_internal
        P = np.asarray(penalized.penalty_local, dtype=np.float64)
        if P.shape != (K, k, k):
            raise ValueError("An sz factor needs one penalty block per level.")
        roots = _penalty_roots(P)
        self._roots = roots
        w = q + 2
        sqrt_tau = math.sqrt(_DEFERRAL_FACTOR * k * _EPS)
        # the unreduced column norms: the deferral's yardstick and the bound's scales
        a2 = _leaf_column_norms2(leaf)
        node_a2 = _node_column_norms(
            tree.child, tree.h, np.ascontiguousarray(a2[:, :k] + np.diagonal(P, axis1=1, axis2=2))
        )

        # First pass: the deferral decisions from the leaves' s-blocks.
        w_first = np.arange(w, dtype=np.int64)
        if leaf.signed:
            R0 = np.zeros((K, k + w, k + w))
            M0 = np.zeros((K, k + w, k + w))
            _signed_leaf_exports(
                np.ascontiguousarray(leaf.pseudo_rows),
                np.ascontiguousarray(leaf.signature),
                roots,
                k,
                w_first,
                R0,
                M0,
            )
            Es = np.ascontiguousarray(R0[:, :k, :k])
        else:
            Es = np.zeros((K, k, k))
            Ex_w = np.zeros((K, k, w))
            Qw = np.zeros((w, w))
            _leaf_exports(leaf.top, roots, k, w_first, Es, Ex_w, Qw)
        deferred = np.zeros((n_int, k), dtype=np.bool_)
        _decide(
            Es, tree.child, tree.h, k, sqrt_tau, np.sqrt(node_a2), deferred, np.zeros((n_int, k, k))
        )
        carry_pos = np.full((n_int, k), -1, dtype=np.int64)
        count = int(np.count_nonzero(deferred))
        carry_pos[deferred] = 1 + np.arange(count)
        self.deferred = count
        self._deferred_mask = deferred
        self._carry_pos = carry_pos
        c = count
        n_ext = 1 + c + q + 1
        n_x = n_ext - 1
        w_pos = np.concatenate(([0], 1 + c + np.arange(q), [1 + c + q])).astype(np.int64)
        self._carried = c
        self._n_x = n_x
        self._border_x = (1 + c + np.arange(q)).astype(np.intp)

        # Second pass: every merge with every column.
        Rzz = np.zeros((n_int, k, k))
        Rzx = np.zeros((n_int, k, k + n_ext))
        rank = np.zeros(n_int, dtype=np.int64)
        Qx = np.zeros((n_ext, n_ext))
        self._kappa = self._sigma_extra = self._middle_norm = None
        if leaf.signed:
            size_e = k + n_ext
            position = np.concatenate((np.arange(k), k + w_pos))
            R_leaf = np.zeros((K, size_e, size_e))
            M_leaf = np.zeros((K, size_e, size_e))
            R_leaf[:, position[:, None], position[None, :]] = R0
            M_leaf[:, position[:, None], position[None, :]] = M0
            # the bound reads each leaf middle factor's largest entry alone: keep
            # that (K,) and free the (K, p, p) exports before the sweep (Opus
            # review P1: a factor held a stack of middle factors for its lifetime)
            leaf_middle_max = np.max(np.abs(M0), axis=(1, 2))
            del R0, M0
            kappa = np.ones(n_int)
            sigma_extra = np.zeros(n_int)
            middle_norm = np.zeros(n_int)
            failed = _signed_sweep(
                R_leaf,
                M_leaf,
                tree.child,
                tree.h,
                k,
                deferred,
                carry_pos,
                np.zeros((n_int, size_e, size_e)),
                np.zeros((n_int, size_e, size_e)),
                Rzz,
                Rzx,
                rank,
                Qx,
                kappa,
                sigma_extra,
                middle_norm,
            )
            if failed >= 0:
                raise np.linalg.LinAlgError(
                    f"FactorSmooth term {self.term_name!r} balance node {failed} has a pivot block "
                    "that is not positive definite (the tree pivot certificate refuses the iterate)."
                )
            self._kappa, self._sigma_extra, self._middle_norm = kappa, sigma_extra, middle_norm
            self._leaf_middle_max = leaf_middle_max
        else:
            E_leaf = np.zeros((K, k, k + n_ext))
            E_leaf[:, :, :k] = Es
            E_leaf[:, :, k + w_pos] = Ex_w
            Qx[np.ix_(w_pos, w_pos)] = Qw + np.asarray(leaf.within, dtype=np.float64)
            _fisher_sweep(
                E_leaf,
                tree.child,
                tree.h,
                k,
                deferred,
                carry_pos,
                np.zeros((n_int, k, k + n_ext)),
                Rzz,
                Rzx,
                rank,
                Qx,
            )
        if not (np.all(np.isfinite(Rzz)) and np.all(np.isfinite(Rzx)) and np.all(np.isfinite(Qx))):
            raise np.linalg.LinAlgError(
                f"FactorSmooth term {self.term_name!r} has a non-representable elimination."
            )
        pivots = np.abs(np.diagonal(Rzz, axis1=1, axis2=2))
        live = np.arange(k)[None, :] < rank[:, None]
        if np.any(live & ~(pivots > 0.0)):
            raise np.linalg.LinAlgError(
                f"FactorSmooth term {self.term_name!r} has a zero balance-tree pivot."
            )
        self._rank_nodes = rank
        self._Rzz = Rzz
        self._Rzx_s = np.ascontiguousarray(Rzx[:, :, :k])  # the pivot rows' s part (row forms)
        self._logdet_tree = float(2.0 * np.sum(np.log(pivots[live])))
        self.minimum_local_diagonal = float(np.min(pivots[live]) ** 2) if np.any(live) else 0.0

        # Down-sweep: Phi, the node solutions and the tree covariance.
        S = np.zeros((K + n_int, k, n_x))
        sigma = np.zeros((K + n_int, k))
        Zx = np.zeros((n_int, k, n_x))
        z0 = np.zeros((n_int, k))
        G_all = np.zeros((n_int, k, k))
        Y_all = np.zeros((n_int, k, k))
        Psi = np.zeros((K + n_int, k, k))
        _down_sweep(
            tree.child,
            tree.h,
            k,
            rank,
            Rzz,
            Rzx,
            deferred,
            carry_pos,
            S,
            sigma,
            Zx,
            z0,
            G_all,
            Y_all,
            Psi,
        )
        self._S, self._sigma, self._Zx = S, sigma, Zx
        self._G_all, self._Y_all, self._Psi = G_all, Y_all, Psi

        Qx = 0.5 * (Qx + Qx.T)
        Q_xx = Qx[:n_x, :n_x]
        self._q_xz = Qx[:n_x, n_x].copy()
        # The super-root: the intercept, eliminated last in the tree (design §3.1).
        # sz leaves the polynomial coordinates unpenalized, so a level with no
        # weight lets the observed levels' constants reproduce the intercept
        # exactly (D_0 = 0): the super-root pivot is then deferred like a tree
        # pivot (decision 3), and the intercept joins the border's certified
        # rank decision.  Otherwise the path is fs's.  Each valid bound
        # (``_border_bound``) is factored, and the one that certifies the
        # higher rank is kept (the first on a tie): a choice of majorant, so
        # the certificate holds either way.
        D0 = float(Q_xx[0, 0])
        self.excluded = tuple(int(index) for index in excluded)
        self._alias_x = self._penalized_aliases(system, P, penalized)
        border = None
        for candidate in self._border_bound(leaf, P, Q_xx, a2, node_a2):
            factored = self._factor_border(Q_xx, candidate, penalized, system)
            if border is None or factored[2].null.shape[1] < border.null.shape[1]:
                self._super_deferred, center_star, border = factored
        assert border is not None
        self._border = border
        self._center_star = center_star
        self._intercept_pivot = D0
        self.border_certificate: BorderCertificate = border.certificate
        self.schur_condition_estimate = border.condition
        self._scaled_eigenvalues_cache: NDArray | None = None
        null = border.null
        if self._super_deferred:
            self._null_x = null
        else:
            self._null_x = np.vstack((-(center_star @ null)[None, :], null))  # (n_x, t)
        coupled, weak_columns, named = self._null_disclosure(P)
        # every column a weak direction moves: the mode certificate leaves their
        # scores ungated (design §3.9); the disclosure names the level that is free
        self.weakly_identified_coefficients: tuple[int, ...] = weak_columns
        self.weakly_identified_named: tuple[int, ...] = named
        self._logdet = float(
            self._logdet_tree
            + k * math.log(K)
            + (0.0 if self._super_deferred else math.log(D0))
            + border.logdet
            + coupled
        )
        self.rank = int(size - null.shape[1])
        self.rank_truncated = self.rank < size

    def _factor_border(self, Q_xx: NDArray, bound: NDArray, penalized, system):
        """``(super_deferred, center_star, border)``: the super-root, then ``factor_border``."""
        D0 = float(Q_xx[0, 0])
        c, n_x = self._carried, self._n_x
        q = len(self._border_x)
        super_deferred = not D0 > bound[0] + 4.0 * _EPS * abs(D0)
        S_small = np.asarray(penalized.penalty_small, dtype=np.float64)
        generators = system.leaf.generators
        if super_deferred:
            lead = 1 + c  # alpha and the carried coordinates ahead of the border
            Q_rest = Q_xx.copy()
            rest_bound = np.array(bound, dtype=np.float64)
            S_rest = np.zeros((n_x, n_x))
            S_rest[lead:, lead:] = S_small
            if generators is not None:
                generators = self._joint_generators(generators, system)
            center_star = np.zeros(n_x - 1)
        else:
            lead = c
            center_star = Q_xx[1:, 0] / D0
            Q_rest = Q_xx[1:, 1:] - D0 * np.outer(center_star, center_star)
            Q_rest = 0.5 * (Q_rest + Q_rest.T)
            diag_full = np.abs(np.diag(Q_xx))[1:]
            rest_bound = (np.sqrt(bound[1:]) + np.abs(center_star) * math.sqrt(bound[0])) ** 2
            rest_bound = rest_bound + 2.0 * _gamma(3) * diag_full
            S_rest = np.zeros((c + q, c + q))
            S_rest[c:, c:] = S_small
            if generators is not None and c:
                generators = generators.shifted(c)
        aliases = self._alias_x
        if aliases is not None and not super_deferred:
            aliases = aliases[1:]  # the super-root has eliminated alpha (a Schur complement)
        if self.excluded:
            positions = self._small_position[np.asarray(self.excluded, dtype=np.intp)]
            if np.any(positions < 1):
                raise ValueError("Only border slope columns can be excluded from an sz factor.")
            rest = lead + positions - 1
            if generators is not None and np.any(generators.matrix[rest]):
                raise ValueError("An excluded border column cannot carry a structural generator.")
            if aliases is not None:
                # an alias through a column the Laplace term leaves out stays with
                # the pivoted factorization (it is not deflated)
                aliases = aliases[:, ~np.any(aliases[rest] != 0.0, axis=0)]
            Q_rest, S_rest, rest_bound = Q_rest.copy(), S_rest.copy(), rest_bound.copy()
            Q_rest[rest, :] = Q_rest[:, rest] = 0.0
            S_rest[rest, :] = S_rest[:, rest] = 0.0
            rest_bound[rest] = 0.0
        if aliases is not None and aliases.shape[1]:
            generators = _append_generators(generators, aliases, self.term_name)
        border = factor_border(
            Q_rest,
            S_rest,
            rest_bound,
            generators,
            term_name=self.term_name,
            term_kind="FactorSmooth term",
        )
        return super_deferred, center_star, border

    def _penalized_aliases(self, system, P: NDArray, penalized) -> NDArray | None:
        """The thin levels' data-null directions the border penalty identifies, ``(n_x, g)``.

        A thin level ``t`` (``d_t`` distinct weighted ``x`` values, fewer than
        the dimension ``m`` of the level penalty's null space ``N_P``) has the
        exact data nulls ``beta_t += N_P f (K - 1) / K``, ``beta_l -= N_P f / K``
        for every other level, and the border taking ``+g(x)' f / K``, for
        every ``f`` with ``g(x)' f = 0`` on the level's ``x`` values (``g =
        N_P' z``, the null-space functions; design §3.5, the alias with the
        required global Spline).  In ``x = [alpha | carried | border]`` their
        tree part is ``z_v = h_v(t) N_P f`` on the deferred ``(v, j)``
        (``sum_l h_v(l) = 0``).  The data part of the border Schur complement
        vanishes along every one of them for every working weight (they are
        nulls of ``[1, X]`` on the weighted rows, and the tree penalty
        vanishes on their tree part), so their curvature is the border
        penalty's alone: smoothing-parameter-scaled, never a rounding
        decision.  Truncated as data, as before, it crossed the certified
        tolerance with lambda and the published ``log|H|`` jumped by the log
        of the tolerance between nearby evaluations (REML's line search then
        failed).  They are therefore deflated structurally (design §3.6
        step 1: data part zero by construction, curvature from ``S``).  Only
        the combinations the penalty certifies (curvature above the
        rounding of the quadratic form; a test invariant to rescaling the
        penalty, so the same at every lambda: Wood, Pya & Safken 2016,
        §3.1.2, an identifiability test that does not depend on the
        smoothing parameters) are returned; the exact nulls stay with the
        pivoted factorization, which truncates them as before.

        ``N_P`` is the shared null space of the level blocks, each scaled to
        unit norm; ``f`` spans the null space of the level's ``sqrt|w|``
        triangle on ``N_P`` beyond its ``d_t`` distinct rows (a level with no
        weight frees all of ``N_P``); the border part is the least-squares
        representation of the null-space functions over every level's
        triangle, kept only when it reproduces them to within ``sqrt(eps)``
        (else the border cannot represent them and there is no alias).
        ``None`` without thin levels or penalty.
        """
        counts = getattr(system, "thin_counts", None)
        if counts is None or not len(counts[0]):
            return None
        levels, distinct = counts
        K, k = self.n_levels, self.block_size
        c, n_x = self._carried, self._n_x
        q = len(self._border_x)
        S_b = np.asarray(penalized.penalty_small, dtype=np.float64)
        if not np.any(S_b):
            return None
        norms = np.sqrt(np.einsum("lij,lij->l", P, P))
        live = norms > 0.0
        if not np.any(live):
            return None
        balanced = np.sum(P[live] / norms[live, None, None], axis=0)
        values, vectors = np.linalg.eigh(0.5 * (balanced + balanced.T))
        null = values <= k * _EPS * max(float(values[-1]), 0.0)
        N_P = vectors[:, null]
        m = N_P.shape[1]
        if not m:
            return None
        # The leaf keeps no whole triangles (Opus review P1): each level's is
        # upper triangular, so its rows below the leading ``k`` are zero on the
        # level basis.  The null-space functions' rows are the leading rows'
        # alone, and the intercept and border rows are the leading rows' and the
        # trailing rows', read through their triangular factor (``trailing_root``,
        # an orthogonal map of the stacked trailing rows, which keeps every Gram
        # and every product's norm; not their Gram, whose rounding would swamp
        # the cancelling residual below).
        leaf = system.leaf
        top = np.asarray(leaf.top, dtype=np.float64)
        RZ = np.matmul(top[:, :, :k], N_P)  # (K, k, m): the null-space functions' rows
        RB = top[:, :, k : k + 1 + q]  # (K, k, 1 + q): intercept and border rows
        tail = np.asarray(leaf.trailing_root(), dtype=np.float64)  # (r, 1 + q), zero on z
        if tail.shape[1] != 1 + q:
            raise ValueError("The sz leaf's trailing rows do not match its border.")
        G_BB = np.einsum("lai,laj->ij", RB, RB) + np.einsum("ai,aj->ij", tail, tail)
        G_BZ = np.einsum("lai,laj->ij", RB, RZ)
        # Jacobi-equilibrated: a smooth's reparametrised columns scale with its
        # lambda (``1e-5`` of the others at lambda 1e10), and the raw Gram's
        # condition (``1e14``) would cost the representation its accuracy
        diagonal = np.diag(G_BB)
        scale = np.zeros_like(diagonal)
        scale[diagonal > 0.0] = 1.0 / np.sqrt(diagonal[diagonal > 0.0])
        scaled = scipy.linalg.lstsq(
            scale[:, None] * G_BB * scale[None, :],
            scale[:, None] * G_BZ,
            cond=(1 + q) * _EPS,
            check_finite=False,
        )[0]
        U = scale[:, None] * scaled
        residual = RZ - np.matmul(RB, U)
        tail_residual = np.einsum(
            "ai,ij->aj", tail, U
        )  # the trailing rows' share: RZ is zero there
        misfit = math.sqrt(
            float(np.sum(residual * residual)) + float(np.sum(tail_residual * tail_residual))
        )
        size = float(np.sqrt(np.sum(RZ * RZ)))
        if not size > 0.0 or misfit > math.sqrt(_EPS) * size:
            return None
        tree = self._tree
        columns = []
        for level, count in zip(levels, distinct, strict=True):
            free = m - int(count)
            if free <= 0:
                continue
            if int(count) == 0:
                F = np.eye(m)
            else:
                F = np.linalg.svd(RZ[level], full_matrices=True)[2][int(count) :].T
            for f in F.T:
                vector = np.zeros(n_x)
                representation = U @ (f / K)
                vector[0] = representation[0]
                vector[1 + c :] = representation[1:]
                if c:
                    shift = N_P @ f
                    for node in range(tree.n_internal):
                        lo, hi = int(tree.lo[node]), int(tree.hi[node])
                        if not lo <= int(level) < hi:
                            continue
                        side = 0 if int(level) < lo + (hi - lo + 1) // 2 else 1
                        deferred = np.flatnonzero(self._deferred_mask[node])
                        vector[self._carry_pos[node, deferred]] = (
                            tree.h[node, side] * shift[deferred]
                        )
                columns.append(vector)
        if not columns:
            return None
        aliases = np.column_stack(columns)
        border = aliases[1 + c :]
        curvature = border.T @ S_b @ border
        values, vectors = np.linalg.eigh(0.5 * (curvature + curvature.T))
        # the rounding of each combination's quadratic form, on its entries before
        # they cancel: a combination whose border part cancels (an exact null of
        # the penalty as well) is left with rounding alone, below this
        spread = np.abs(border) @ np.abs(vectors)
        magnitude = np.einsum("it,ij,jt->t", spread, np.abs(S_b), spread)
        certified = values > (q + 2 + len(values)) * _EPS * magnitude
        if not np.any(certified):
            return None
        return aliases @ vectors[:, certified]

    def _joint_generators(self, generators, system) -> BorderGenerators:
        """The border generators over ``[alpha | carried | border]`` (super-root deferred).

        A complete one-hot block's sum is the intercept column, so with the
        intercept still in the border the exact null is ``1_g - e_alpha``: the
        intercept coefficient of a generator is minus its data column's
        (integer) value, ``g' X'W1 / sum w`` rounded (one-hot columns and small
        integer generators make it exact in exact arithmetic).
        """
        c = self._carried
        n_x = self._n_x
        matrix = np.zeros((n_x, generators.count))
        matrix[1 + c :] = generators.matrix
        value = generators.matrix.T @ np.asarray(system.xtw_small, dtype=np.float64) / system.sum_w
        matrix[0] = -np.round(value)
        return BorderGenerators(matrix, generators.references + 1 + c, generators.labels)

    # -- the bound ----------------------------------------------------------------
    def _border_bound(
        self, leaf, P: NDArray, Q_xx: NDArray, a2: NDArray, node_a2: NDArray
    ) -> list[NDArray]:
        """Majorants ``U`` ``(n_x,)``, each with ``|dQ_ij| <= sqrt(U_i U_j)`` on the Gram.

        The Gram is the intercept-and-border one; the majorants differ only in
        their free ``t`` (below).

        Every rounding is a columnwise backward error of a Householder stage on
        disjoint row sets (Higham 2002, Theorem 19.4; the tree and TSQR, Demmel
        et al., arXiv 0808.2664): the leaf pass (per level, as block_leaves),
        the leaf trial, and at most ``depth`` merges on any row's path, each
        also carrying the balance multiplier's own rounding.  In node
        coordinates it gives ``||dA v_j|| <= eta_j``; the Schur complement
        then moves by ``eta_i r_j + r_i eta_j`` at first order (the elimination
        vector is the least-squares one, so its own change is second order) and
        by ``s_i s_j`` beyond, ``s_j = 2 eta_j + sqrt(omega)(r_j + 2 eta_j)``,
        ``omega >= ||dA_T H_T^-1/2||^2``.  Majorised by ``sqrt(U_i U_j)`` with
        ``U_j = t r_j^2 + eta_j^2 / t + s_j^2`` (Cauchy-Schwarz, one global
        ``t`` as block_leaves), plus the Gram sums' own rounding.  Signed rows
        add the sandwiched errors of block_leaves' signed bound per leaf and,
        per merge, the middle factor's product and Schur step on the subtree's
        rows.
        """
        top = leaf.top
        K, p = top.shape[0], top.shape[2]
        k = leaf.block_size
        n_x = self._n_x
        c = self._carried
        q = len(self._border_x)
        tree = self._tree
        n_int = tree.n_internal
        S_leaf = self._S[:K]  # beta_l per unit x_j: (K, k, n_x)
        counts = leaf.counts.astype(np.float64)
        merges = leaf.merges.astype(np.float64)
        # the level rows' columns [z | intercept | border | rhs] -> x positions
        x_of_w = np.concatenate(([0], self._border_x)).astype(np.intp)  # w columns but rhs
        # augmented unsigned residuals per level: R_l [beta_lj; e_j] and the penalty
        # rows; the triangle's rows below its leading k are zero on the level
        # basis, so theirs is the trailing rows' column norm whatever beta is
        residual = np.matmul(top[:, :, :k], S_leaf)
        residual[:, :, x_of_w] += top[:, :, k : k + 1 + q]
        penalty_part = np.matmul(self._roots, S_leaf)
        r2_level = np.sum(residual**2, axis=1)
        r2_level[:, x_of_w] += leaf.tail_norms2[:, : 1 + q]
        r2_level = r2_level + np.sum(penalty_part**2, axis=1)  # (K, n_x)
        # column scales of the level rows (data, ``a2``) and of the penalty
        a_z = np.sqrt(np.maximum(a2[:, :k] + np.diagonal(P, axis1=1, axis2=2), 0.0))
        a_x_level = np.zeros((K, n_x))
        a_x_level[:, x_of_w] = np.sqrt(np.maximum(a2[:, k : k + 1 + q], 0.0))
        # per-level row-stage factors (leaf pass, leaf trial)
        m_trial = (p + k) if leaf.signed else 2 * k
        g_level = (
            2.0 * _gamma_array(2.0 * np.maximum(counts, 1.0) * p)
            + 2.0 * merges * _gamma(4.0 * p * p)
            + 2.0 * _gamma(2.0 * m_trial * p)
            + _gamma(2)
        )
        if leaf.signed:
            g_level = g_level + math.sqrt(p) * _gamma(p + 1)
        eta_level = g_level[:, None] * (
            a_x_level + np.matmul(a_z[:, None, :], np.abs(S_leaf))[:, 0, :]
        )
        # node-coordinate column norms of the tree and the carried coordinates
        node_a = np.sqrt(node_a2)
        a_x = np.sqrt(np.sum(a_x_level**2, axis=0))
        if c:
            nodes, coords = np.nonzero(self._deferred_mask)
            a_x[self._carry_pos[nodes, coords]] = node_a[nodes, coords]
        eliminated = ~self._deferred_mask
        tree_part = np.einsum("vk,vke->e", np.where(eliminated, node_a, 0.0), np.abs(self._Zx))
        width = 2 * k + self._n_x + 1
        rows_merge = (2 * (k + self._n_x + 1)) if leaf.signed else 2 * k
        g_merge = 2.0 * _gamma(2.0 * rows_merge * width) + 2.0 * _UNIT
        eta_tree = tree.depth * g_merge * (a_x + tree_part)
        eta = np.sqrt(np.sum(eta_level**2, axis=0)) + eta_tree
        r2 = np.sum(r2_level, axis=0)
        r = np.sqrt(np.maximum(r2, 0.0))
        # second order: omega >= ||dA_T H_T^-1/2||^2 <= g^2 n_T tr(D_a H_T^-1 D_a)
        g_all = float(np.max(g_level, initial=0.0)) + tree.depth * g_merge
        Y = self._Y_all
        G = self._G_all
        Psi_node = self._Psi[K:]
        conditional = np.sum(np.matmul(G, Psi_node) * G, axis=2) + np.sum(Y * Y, axis=2)
        n_tree = int(np.count_nonzero(eliminated))
        omega = (
            2.0
            * g_all**2
            * n_tree
            * float(np.sum(np.where(eliminated, node_a2 * conditional, 0.0)))
        )
        if omega >= 0.25:
            omega = float("inf")
        second = (2.0 * eta + math.sqrt(omega) * (r + 2.0 * eta)) ** 2
        # t is free (the majorant holds for every t > 0); it minimises the
        # Jacobi-scaled sum over the columns resolved above their rounding.  A
        # column whose Schur diagonal is within 4 eta (r + eta) of zero is an
        # exact null whatever t is (U_j >= 2 eta_j r_j at the best t), and its
        # eta^2 / d_j would otherwise decide t: an sz term with a weightless
        # level or no penalty aliases the super-root or a main effect with the
        # tree, and both hold only rounding in d_j and r_j.  An eps-level pivot
        # can decide it too: a column whose Schur diagonal is at most 20 k eps
        # of its unreduced column's norm squared, the deferral's own yardstick
        # (decision 3; a carried coordinate always is one, and so is a
        # super-root aliased with the levels).  Its rounding can be a large
        # share of its diagonal, and at its t every column's bound grows to that
        # share (border rank 0 on one-row levels under a log link).  So a
        # second majorant takes t from the other columns, at which such a
        # pivot is resolved or an exact null by its own bound; the caller
        # keeps the one that certifies the higher rank.
        d = np.abs(np.diag(Q_xx))
        alive = d > 4.0 * eta * (np.sqrt(np.maximum(r2, 0.0)) + eta)
        resolved = alive & (d > _DEFERRAL_FACTOR * self.block_size * _EPS * a_x**2)
        rbar = r + eta
        rows_total = float(np.sum(counts) + K * (p + k) + n_int * 2 * k)
        floor = second + _gamma(rows_total + 1.0) * rbar**2
        if leaf.signed:
            floor = floor + self._signed_sandwich(
                leaf, counts, merges, p, m_trial, r2_level, eta_level
            )
        bounds = []
        second_choice = np.any(resolved) and np.any(alive & ~resolved)
        for chosen in (alive, resolved) if second_choice else (alive,):
            rho = float(np.sum(r2[chosen] / d[chosen])) if np.any(chosen) else 0.0
            nu = float(np.sum(eta[chosen] ** 2 / d[chosen])) if np.any(chosen) else 0.0
            t = math.sqrt(nu / rho) if rho > 0.0 and nu > 0.0 else 1.0
            bounds.append(np.nextafter(t * r2 + eta**2 / t + floor, np.inf))
        return bounds

    def _signed_sandwich(self, leaf, counts, merges, p, m_trial, r2_level, eta_level) -> NDArray:
        """Signed rows' sandwiched errors: block_leaves' per-level sigma and the merges' own.

        A middle factor's error ``dM`` enters ``Q`` at first order as ``(R v_i)'
        dM (R v_j)``, and ``||R v_j||`` is the unsigned norm of the subtree's rows
        on ``v_j``: at most ``rbar_j`` summed over the subtree's levels.
        """
        K = r2_level.shape[0]
        tree = self._tree
        n_int = tree.n_internal
        rbar2_level = (np.sqrt(np.maximum(r2_level, 0.0)) + eta_level) ** 2
        kappa, sigma_extra, middle_norm = self._kappa, self._sigma_extra, self._middle_norm
        assert kappa is not None and sigma_extra is not None and middle_norm is not None
        sigma_level = (
            2.0 * math.sqrt(p) * _gamma_array(2.0 * np.maximum(counts, 1.0) * p)
            + p * _gamma_array(np.maximum(counts, 1.0))
            + p * p * _UNIT
            + 2.0 * math.sqrt(p) * _gamma(2.0 * m_trial * p)
            + p * _gamma(m_trial)
            + merges * (2.0 * math.sqrt(p) * _gamma(4.0 * p * p) + p * _gamma(2.0 * p))
        )
        sigma_level = sigma_level * (1.0 + self._leaf_middle_max)
        total = np.einsum("l,le->e", sigma_level, rbar2_level)
        size = self._n_x + 1 + leaf.block_size
        width = 2 * leaf.block_size + self._n_x + 1
        rows = 2 * size
        sub = np.zeros((K + n_int, rbar2_level.shape[1]))
        sub[:K] = rbar2_level
        for node in range(n_int):
            for side in range(2):
                child = int(tree.child[node, side])
                sub[K + node] += sub[-child - 1] if child < 0 else sub[K + child]
            own = (
                2.0 * math.sqrt(width) * _gamma(2.0 * rows * width) * middle_norm[node]
                + width * _gamma(rows) * middle_norm[node]
                + sigma_extra[node]
            )
            own = own + own * own * kappa[node]
            total = total + own * sub[K + node]
        return total

    # -- disclosure and the coupled pseudo-determinant --------------------------
    def _null_disclosure(self, P: NDArray) -> tuple[float, tuple[int, ...], tuple[int, ...]]:
        """``log det(n'n)``, the weakly identified columns, and those a weak direction names.

        The null vectors of ``H_c`` in public coordinates are generated by an
        orthonormal basis ``Z`` of ``Q_rest``'s null space (unscaled): the
        border rows of ``Z``, and the levels ``Phi_l [alpha; Z]`` with the
        intercept component dropped (module docstring).

        Each null direction is then classified and disclosed on its resolved
        entries (``_resolved_null_directions``, and the rounding of the
        direction's own computation, ``sqrt(eps)`` of its largest entry, as
        ``border.factor_border``).  A direction whose penalty curvature
        ``sum_l beta_l' P_l beta_l + x_b' S_b x_b`` exceeds the rounding of the
        quadratic form is not an exact null of ``H`` (Fisher rows' data part
        is positive semidefinite): weakly identified (design §3.6 step 5).
        The others are the exact aliases.  A weak direction leaves the score
        of every column it moves ungated (each entry above ``sqrt(eps)`` of
        its largest), and it names the columns it moves in its own right: the
        border entries it resolves (``_resolved_null_directions``), so the
        noise a truncated direction carries on unrelated columns is not
        named, and on the levels the entries that stand above the shift it
        gives every level alike.  The sum-to-zero constraint spreads a free
        level deviation ``d`` over all levels as ``-d / K`` and the main
        effect takes ``+d / K``: that shared shift is the per-coordinate
        median across levels whenever fewer than half the levels are free,
        and what stands above it, beyond the resolution, is the level whose
        data cannot place it.
        """
        null = self._border.null
        t = null.shape[1]
        K, k = self.n_levels, self.block_size
        if not t:
            return 0.0, (), ()
        Z = np.linalg.qr(null)[0]
        if self._super_deferred:
            x_vectors = Z
        else:
            x_vectors = np.vstack((-(self._center_star @ Z)[None, :], Z))
        levels = np.einsum("lke,et->lkt", self._S[:K], x_vectors)
        border_part = x_vectors[1 + self._carried :]
        public = np.concatenate((levels[: K - 1].reshape((K - 1) * k, t), border_part), axis=0)
        sign, value = np.linalg.slogdet(public.T @ public)
        coupled = float(value) if sign > 0 else 0.0

        x_raw, x_noise = self._resolved_null_directions()
        beta = np.einsum("lke,et->lkt", self._S[:K], x_raw)
        beta_noise = np.einsum("lke,et->lkt", np.abs(self._S[:K]), x_noise)
        first = 1 + self._carried
        # an entry counts above its propagated resolution and the rounding of
        # its own computation, sqrt(eps) of the direction's largest entry (as
        # border.factor_border): below both it is not part of the direction
        largest = np.maximum(
            np.max(np.abs(beta), axis=(0, 1), initial=0.0),
            np.max(np.abs(x_raw[first:]), axis=0, initial=0.0),
        )
        floor = math.sqrt(_EPS) * largest
        beta_noise = beta_noise + floor[None, None, :]
        x_noise = x_noise + floor[None, :]
        beta = np.where(np.abs(beta) > beta_noise, beta, 0.0)
        border_raw = np.where(np.abs(x_raw[first:]) > x_noise[first:], x_raw[first:], 0.0)
        S_b = np.asarray(self.penalized.penalty_small, dtype=np.float64)
        curvature = np.einsum("lkt,lkj,ljt->t", beta, P, beta) + np.einsum(
            "it,ij,jt->t", border_raw, S_b, border_raw
        )
        magnitude = np.einsum("lkt,lkj,ljt->t", np.abs(beta), np.abs(P), np.abs(beta)) + np.einsum(
            "it,ij,jt->t", np.abs(border_raw), np.abs(S_b), np.abs(border_raw)
        )
        weak = curvature > (public.shape[0] + 2) * _EPS * magnitude
        moved: set[int] = set()
        named: set[int] = set()
        border_indices = self.small_indices[1:]
        public_indices = np.concatenate((self.structured_indices.ravel(), border_indices))
        whole = np.einsum("lke,et->lkt", self._S[:K], self._null_x)
        for index in np.flatnonzero(weak):
            vector = np.abs(
                np.concatenate((whole[: K - 1, :, index].ravel(), self._null_x[first:, index]))
            )
            moved.update(
                int(c)
                for c in public_indices[
                    vector > math.sqrt(_EPS) * float(np.max(vector, initial=0.0))
                ]
            )
            named.update(int(column) for column in border_indices[border_raw[:, index] != 0.0])
            # the median is one level's entry (or the mean of two): its noise is
            # at most the largest of theirs
            piece, noise = beta[:, :, index], beta_noise[:, :, index]
            excess = np.abs(piece - np.median(piece, axis=0)[None, :])
            free = excess > noise + np.max(noise, axis=0)[None, :]
            for level, coordinate in zip(*np.nonzero(free), strict=True):
                if level < K - 1:
                    named.add(int(self.structured_indices[level, coordinate]))
                else:  # the last level is minus the sum of the public ones
                    named.update(int(c) for c in self.structured_indices[:, coordinate])
        return coupled, tuple(sorted(moved)), tuple(sorted(named))

    def _resolved_null_directions(self) -> tuple[NDArray, NDArray]:
        """The border null directions over ``x`` ``(n_x, t)``, with each entry's resolution.

        ``factor_border`` returns exact nulls (unit columns, by their own
        bound) and an orthonormal basis ``Z`` of the truncated subspace of the
        scaled live matrix ``Q_s``.  Only that subspace carries an error: with
        ``||dQ_s||_2 <= u_s`` (the certificate), Ritz values ``Theta`` and
        residual ``R = Q_s Z - Z Theta``, the Davis-Kahan sin-theta theorem in
        its residual form (Davis & Kahan 1970; Stewart & Sun 1990, Theorem
        V.3.6) bounds the angle to the true subspace by ``sin <= (||R|| + u_s)
        / delta``, ``delta = lambda_{r+1}(Q_s) - u_s - max Theta`` the
        separation from the retained spectrum (Weyl).  ``Z`` then lies within
        ``sqrt(2) sin`` of an orthonormal basis of the true subspace (the step
        from angles to bases in Yu, Wang & Samworth 2015, proof of Theorem 2),
        so each entry is known to ``sqrt(2) sin`` in the scaled coordinates,
        and to ``sqrt(2) sin ||E_j||`` in ``x``, ``E`` the map from the scaled
        coordinates to ``x`` (the unscaling, the structural elimination and,
        with the super-root eliminated, ``alpha = -c*' x_rest``).  Entries
        within it are set to zero; without a separation below one nothing is
        resolved, and the directions are returned whole with no allowance
        (every entry counts).
        """
        border = self._border
        source = border.source
        certificate = border.certificate
        null = border.null
        t = null.shape[1]
        m = null.shape[0]
        if source is None:
            return self._lift_rest(null), np.zeros((self._n_x, t))
        width = len(source.scale)
        # E: scaled deflated coordinates -> rest coordinates -> x
        E = np.zeros((m, width))
        E[source.M, np.arange(width)] = source.scale
        if source.deflation is not None:
            N, _references = source.deflation
            E += N @ (-(source.G.T * source.scale[None, :]))
        E_x = self._lift_rest(E)
        scaled = np.array(source.null_scaled, dtype=np.float64, copy=True)
        exact = certificate.exact_null
        live = np.asarray(source.live, dtype=np.intp)
        trailing = scaled.shape[1] - exact
        sine = 0.0
        if trailing:
            Qs = border.scaled_matrix[np.ix_(live, live)]
            basis = scaled[np.ix_(live, np.arange(exact, exact + trailing))]
            product = Qs @ basis
            rayleigh = basis.T @ product
            rayleigh = 0.5 * (rayleigh + rayleigh.T)
            residual = float(np.linalg.norm(product - basis @ rayleigh, 2))
            spectrum = np.linalg.eigvalsh(0.5 * (Qs + Qs.T))
            separation = (
                float(spectrum[trailing])
                - certificate.u_s
                - float(np.linalg.eigvalsh(rayleigh)[-1])
                if trailing < len(live)
                else 0.0
            )
            sine = (residual + certificate.u_s) / separation if separation > 0.0 else float("inf")
        resolution = math.sqrt(2.0) * sine
        noise = np.zeros((self._n_x, t))
        if trailing and resolution < 1.0:
            block = scaled[:, exact:]
            block[np.abs(block) <= resolution] = 0.0
            noise[:, exact:] = (resolution * np.linalg.norm(E_x, axis=1))[:, None]
        # (no separation: nothing is resolved, and every entry counts, as a rank decision)
        return E_x @ scaled, noise

    def _lift_rest(self, values: NDArray) -> NDArray:
        """Rest-coordinate vectors ``(m, r)`` as ``x = [alpha | carried | border]`` ``(n_x, r)``."""
        if self._super_deferred:
            return np.array(values, dtype=np.float64, copy=True)
        return np.vstack((-(self._center_star @ values)[None, :], values))

