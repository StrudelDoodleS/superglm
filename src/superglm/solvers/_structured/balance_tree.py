# Householder QR in fixed-order loops (LAPACK dlarfg's reflector: beta =
# -sign(alpha) ||x||, tau = (beta - alpha) / beta; Higham 2002 §19.3 and
# Lemma 19.2).  No BLAS, so no result depends on a thread count, and a
# reflector depends on its own column alone: the decision pass and the full
# pass compute the same pivots bit for bit.
@numba.njit(cache=True)
def _norm(A, lo, hi, c):  # pragma: no cover - compiled
    """Scaled 2-norm of ``A[lo:hi, c]`` (no overflow or underflow of the squares)."""
    scale = 0.0
    for i in range(lo, hi):
        value = abs(A[i, c])
        if value > scale:
            scale = value
    if scale == 0.0:
        return 0.0
    total = 0.0
    for i in range(lo, hi):
        value = A[i, c] / scale
        total += value * value
    return scale * math.sqrt(total)


@numba.njit(cache=True)
def _reflect(A, row, c, columns, v, M):  # pragma: no cover - compiled
    """Householder reflector zeroing ``A[row + 1:, c]``, applied to ``columns`` (and to ``M``
    from both sides when ``M`` is not empty).  Returns ``tau``."""
    m = A.shape[0]
    alpha = A[row, c]
    xnorm = _norm(A, row + 1, m, c)
    if xnorm == 0.0:
        return 0.0
    beta = -math.copysign(math.hypot(alpha, xnorm), alpha)
    tau = (beta - alpha) / beta
    scale = 1.0 / (alpha - beta)
    v[row] = 1.0
    for i in range(row + 1, m):
        v[i] = A[i, c] * scale
        A[i, c] = 0.0
    A[row, c] = beta
    for d in columns:
        s = A[row, d]
        for i in range(row + 1, m):
            s += v[i] * A[i, d]
        s *= tau
        A[row, d] -= s
        for i in range(row + 1, m):
            A[i, d] -= s * v[i]
    if M.shape[0]:
        # M <- H M H with H = I - tau v v' on rows/columns row..m
        n = M.shape[0]
        for j in range(n):
            s = M[row, j]
            for i in range(row + 1, m):
                s += v[i] * M[i, j]
            s *= tau
            M[row, j] -= s
            for i in range(row + 1, m):
                M[i, j] -= s * v[i]
        for i in range(n):
            s = M[i, row]
            for j in range(row + 1, m):
                s += M[i, j] * v[j]
            s *= tau
            M[i, row] -= s
            for j in range(row + 1, m):
                M[i, j] -= s * v[j]
    return tau


@numba.njit(cache=True)
def _mm(A, B):  # pragma: no cover - compiled
    """``A @ B`` by fixed-order loops (no BLAS: the result does not depend on a thread count)."""
    m, inner = A.shape
    n = B.shape[1]
    out = np.zeros((m, n))
    for i in range(m):
        for t in range(inner):
            a = A[i, t]
            if a == 0.0:
                continue
            for j in range(n):
                out[i, j] += a * B[t, j]
    return out


@numba.njit(cache=True)
def _others(n, used):  # pragma: no cover - compiled
    count = 0
    for c in range(n):
        if not used[c]:
            count += 1
    out = np.empty(count, np.int64)
    position = 0
    for c in range(n):
        if not used[c]:
            out[position] = c
            position += 1
    return out


@numba.njit(cache=True)
def _leaf_exports(R_acc, roots, k, w_pos, Es, Ex, Qx):  # pragma: no cover - compiled
    """Fisher leaves: ``QR([[R_l[:k]], [sqrt(P_l), 0]])``; ``[E^s | E^x]`` and ``Qx += T'T``.

    ``w_pos`` maps the level rows' ``w`` border columns (intercept, border,
    right-hand side) to ``ext`` positions.  ``R_acc`` ``(K, >= k, p)``: only
    each level's leading ``k`` rows are read.
    """
    K, p = R_acc.shape[0], R_acc.shape[2]
    w = p - k
    m = 2 * k
    empty = np.zeros((0, 0))
    v = np.zeros(m)
    for level in range(K):
        A = np.zeros((m, p))
        for i in range(k):
            for j in range(p):
                A[i, j] = R_acc[level, i, j]
            for j in range(k):
                A[k + i, j] = roots[level, i, j]
        used = np.zeros(p, np.bool_)
        for j in range(k):
            used[j] = True
            _reflect(A, j, j, _others(p, used), v, empty)
        for i in range(k):
            for j in range(k):
                Es[level, i, j] = A[i, j] if j >= i else 0.0
            for t in range(w):
                Ex[level, i, w_pos[t]] = A[i, k + t]
        for r in range(k, m):
            for a in range(w):
                ta = A[r, k + a]
                if ta == 0.0:
                    continue
                for b in range(w):
                    Qx[w_pos[a], w_pos[b]] += ta * A[r, k + b]


@numba.njit(cache=True)
def _decide(Es, child, h, k, sqrt_tau, node_scale, deferred, Es_internal):  # pragma: no cover
    """First pass: the deferral decisions from the ``[z | s]`` columns alone.

    Column ``j`` of ``z_v`` is deferred when its remaining norm is at most
    ``sqrt_tau`` times ``node_scale[v, j]``, the norm of that column in the
    unreduced problem (the subtree's leaf rows and penalty roots in node
    coordinates, ``_node_column_norms``).  The stacked matrix's own column is
    the wrong yardstick: its entries are the children's exports after their
    subtrees were eliminated, so when a subtree is exhausted (one-row or
    weightless levels) that column is itself rounding noise and a
    rounding-level remainder never looks small against it.  Householder QR's
    rounding in column ``j`` is bounded by ``gamma`` times the unreduced
    column's norm (Higham 2002, Theorem 19.4), so a remainder below
    ``sqrt_tau`` of it is not a pivot.  ``Es`` holds the leaves' ``E^s``;
    ``Es_internal`` receives the nodes'.
    """
    n_int = child.shape[0]
    m = 2 * k
    empty = np.zeros((0, 0))
    v = np.zeros(m)
    for node in range(n_int):
        root = node == n_int - 1
        width = k if root else 2 * k
        A = np.zeros((m, width))
        for side in range(2):
            c = child[node, side]
            factor = h[node, side]
            base = side * k
            for i in range(k):
                for j in range(k):
                    e = Es[-c - 1, i, j] if c < 0 else Es_internal[c, i, j]
                    A[base + i, j] = factor * e
                    if not root:
                        A[base + i, k + j] = e
        used = np.zeros(width, np.bool_)
        row = 0
        for j in range(k):
            remaining = _norm(A, row, m, j)
            if remaining <= sqrt_tau * node_scale[node, j]:
                deferred[node, j] = True
                continue
            used[j] = True
            _reflect(A, row, j, _others(width, used), v, empty)
            row += 1
        if root:
            continue
        for j in range(k):
            used[k + j] = True
            _reflect(A, row, k + j, _others(width, used), v, empty)
            row += 1
        rank = 0
        for j in range(k):
            if not deferred[node, j]:
                rank += 1
        for i in range(k):
            for j in range(k):
                Es_internal[node, i, j] = A[rank + i, k + j] if j >= i else 0.0


@numba.njit(cache=True)
def _stack(node, child, h, k, root, deferred, carry_pos, E_leaf, E_int, rows_per, n_ext):
    """The merge's stacked matrix ``[z_e | s | ext]``, deferred ``z`` columns moved to ext.

    ``E_leaf``/``E_int`` are the children's exports over ``[s | ext]``
    (``rows_per`` rows each); ``carry_pos[node, j]`` is the ext column of a
    deferred coordinate.
    """  # pragma: no cover - compiled
    rank = 0
    for j in range(k):
        if not deferred[node, j]:
            rank += 1
    s_count = 0 if root else k
    width = rank + s_count + n_ext
    A = np.zeros((2 * rows_per, width))
    offset = rank + s_count
    for side in range(2):
        c = child[node, side]
        factor = h[node, side]
        base = side * rows_per
        for i in range(rows_per):
            column = 0
            for j in range(k):
                e = E_leaf[-c - 1, i, j] if c < 0 else E_int[c, i, j]
                if deferred[node, j]:
                    A[base + i, offset + carry_pos[node, j]] = factor * e
                else:
                    A[base + i, column] = factor * e
                    column += 1
                if not root:
                    A[base + i, rank + j] = e
            for t in range(n_ext):
                A[base + i, offset + t] += E_leaf[-c - 1, i, k + t] if c < 0 else E_int[c, i, k + t]
    return A, rank


@numba.njit(cache=True)
def _fisher_sweep(E_leaf, child, h, k, deferred, carry_pos, E_int, Rzz, Rzx, rank_out, Qx):
    """Second pass, Fisher rows: every merge with every column, the decisions fixed.

    Exports are ``k x (k + n_ext)`` over ``[s | ext]``; ``Rzx`` holds the pivot
    rows over ``[s | ext]`` (the root's over ``ext``, shifted by ``k``); the
    rows below the export go to the border Gram ``Qx``.
    """  # pragma: no cover - compiled
    n_int = child.shape[0]
    n_ext = E_leaf.shape[2] - k
    empty = np.zeros((0, 0))
    v = np.zeros(2 * k)
    for node in range(n_int):
        root = node == n_int - 1
        A, rank = _stack(node, child, h, k, root, deferred, carry_pos, E_leaf, E_int, k, n_ext)
        m, width = A.shape
        s_count = 0 if root else k
        used = np.zeros(width, np.bool_)
        for j in range(rank + s_count):
            used[j] = True
            _reflect(A, j, j, _others(width, used), v, empty)
        rank_out[node] = rank
        offset = rank + s_count
        for i in range(rank):
            for t in range(rank):
                Rzz[node, i, t] = A[i, t] if t >= i else 0.0
            for j in range(s_count):
                Rzx[node, i, j] = A[i, rank + j]
            for t in range(n_ext):
                Rzx[node, i, k + t] = A[i, offset + t]
        if not root:
            for i in range(k):
                for j in range(k + n_ext):
                    E_int[node, i, j] = A[rank + i, rank + j] if j >= i else 0.0
        for r in range(offset, m):
            for a in range(n_ext):
                ta = A[r, offset + a]
                if ta == 0.0:
                    continue
                for b in range(n_ext):
                    Qx[a, b] += ta * A[r, offset + b]


@numba.njit(cache=True)
def _signed_leaf_exports(B, signature, roots, k, w_pos, R_out, M_out):  # pragma: no cover
    """Signed leaves: ``QR([[B_l], [sqrt(P_l), 0]])`` with its middle factor ``Q'JQ``.

    The export is the triangle over ``[s | ext]`` and its middle factor
    (Bojanczyk, Higham & Patel 2003; block_leaves' signed trial without the
    elimination), scattered to the ext positions ``w_pos``.
    """
    K, p, _ = B.shape
    w = p - k
    m = p + k
    v = np.zeros(m)
    position = np.empty(p, np.int64)
    for j in range(k):
        position[j] = j
    for t in range(w):
        position[k + t] = k + w_pos[t]
    for level in range(K):
        A = np.zeros((m, p))
        M = np.zeros((m, m))
        for i in range(p):
            for j in range(p):
                A[i, j] = B[level, i, j]
            M[i, i] = signature[level, i]
        for i in range(k):
            for j in range(k):
                A[p + i, j] = roots[level, i, j]
            M[p + i, p + i] = 1.0
        used = np.zeros(p, np.bool_)
        for j in range(p):
            used[j] = True
            _reflect(A, j, j, _others(p, used), v, M)
        for i in range(p):
            for j in range(p):
                if j >= i:
                    R_out[level, position[i], position[j]] = A[i, j]
                M_out[level, position[i], position[j]] = 0.5 * (M[i, j] + M[j, i])


@numba.njit(cache=True)
def _signed_sweep(
    R_leaf,
    M_leaf,
    child,
    h,
    k,
    deferred,
    carry_pos,
    R_int,
    M_int,
    Rzz,
    Rzx,
    rank_out,
    Qx,
    kappa,
    sigma_extra,
    middle_norm,
):  # pragma: no cover - compiled
    """Second pass, signed rows: QR of ``[z_e | s | ext]`` with its middle factor.

    The pivot certificate is the Cholesky ``M~_zz = L L'`` (block_leaves §3.4
    step 2); a failure returns the node.  With ``N = L^-1 M~_zr`` the pivot is
    ``U = L' R~_zz`` and the effective pivot rows ``L' R~_zr + N R~_rr`` (the
    stationarity of the quadratic form in ``z_e``), so the down-sweep reads
    them as it reads Fisher rows.  The export is ``(R~_rr, M~ / M~_zz)``; the
    root's ``R~_rr' (M~ / M~_zz) R~_rr`` is the border Gram.  Returns ``-1``.
    """
    n_int = child.shape[0]
    size = R_leaf.shape[1]
    n_ext = size - k
    m = 2 * size
    v = np.zeros(m)
    for node in range(n_int):
        root = node == n_int - 1
        A, rank = _stack(node, child, h, k, root, deferred, carry_pos, R_leaf, R_int, size, n_ext)
        width = A.shape[1]
        M = np.zeros((m, m))
        for side in range(2):
            c = child[node, side]
            base = side * size
            for i in range(size):
                for j in range(size):
                    M[base + i, base + j] = M_leaf[-c - 1, i, j] if c < 0 else M_int[c, i, j]
        used = np.zeros(width, np.bool_)
        for j in range(width):
            used[j] = True
            _reflect(A, j, j, _others(width, used), v, M)
        total = 0.0
        for i in range(width):
            for j in range(width):
                total += M[i, j] * M[i, j]
        middle_norm[node] = math.sqrt(total)
        L = np.zeros((rank, rank))
        for j in range(rank):
            s = M[j, j]
            for t in range(j):
                s -= L[j, t] * L[j, t]
            if not s > 0.0:
                return node
            L[j, j] = math.sqrt(s)
            for i in range(j + 1, rank):
                s = 0.5 * (M[i, j] + M[j, i])
                for t in range(j):
                    s -= L[i, t] * L[j, t]
                L[i, j] = s / L[j, j]
        rest = width - rank
        N = np.zeros((rank, rest))
        for c in range(rest):
            for i in range(rank):
                s = 0.5 * (M[i, rank + c] + M[rank + c, i])
                for t in range(i):
                    s -= L[i, t] * N[t, c]
                N[i, c] = s / L[i, i]
        schur = np.empty((rest, rest))
        for i in range(rest):
            for j in range(rest):
                s = 0.5 * (M[rank + i, rank + j] + M[rank + j, rank + i])
                for t in range(rank):
                    s -= N[t, i] * N[t, j]
                schur[i, j] = s
        Linv = np.zeros((rank, rank))
        for c in range(rank):
            for i in range(rank):
                s = 1.0 if i == c else 0.0
                for t in range(i):
                    s -= L[i, t] * Linv[t, c]
                Linv[i, c] = s / L[i, i]
        kf = 0.0
        for i in range(rank):
            for j in range(rank):
                kf += Linv[i, j] * Linv[i, j]
        kappa[node] = kf
        # the Schur step's own rounding (Higham Theorems 8.5 and 10.3), as block_leaves:
        # |dN| <= gamma_r |L^-1| |L| |N|, err = gamma_{r+1} (|M_rr| + |N|'|N|) + 2 |N|' |dN|
        gk = _UNIT * max(rank, 1) / (1.0 - _UNIT * max(rank, 1))
        gk1 = _UNIT * (rank + 1) / (1.0 - _UNIT * (rank + 1))
        absN = np.abs(N)
        dN = gk * _mm(np.abs(Linv), _mm(np.abs(L), absN))
        ef = 0.0
        sf = 0.0
        for i in range(rest):
            for j in range(rest):
                cross = 0.0
                corr = 0.0
                for t in range(rank):
                    cross += absN[t, i] * absN[t, j]
                    corr += absN[t, i] * dN[t, j]
                err = gk1 * (abs(M[rank + i, rank + j]) + cross) + 2.0 * corr
                ef += err * err
                sf += schur[i, j] * schur[i, j]
        g2w = _UNIT * 2 * width / (1.0 - _UNIT * 2 * width)
        sigma_extra[node] = math.sqrt(ef) + g2w * math.sqrt(sf) + max(rank, 1) * gk1
        rank_out[node] = rank
        # pivot U = L' R~_zz and effective rows L' R~_zr + N R~_rr
        for i in range(rank):
            for t in range(rank):
                s = 0.0
                for u in range(i, t + 1):
                    s += L[u, i] * A[u, t]
                Rzz[node, i, t] = s if t >= i else 0.0
            for c in range(rest):
                s = 0.0
                for u in range(i, rank):
                    s += L[u, i] * A[u, rank + c]
                for u in range(c + 1):
                    s += N[i, u] * A[rank + u, rank + c]
                target = c if not root else k + c
                Rzx[node, i, target] = s
        if root:
            Rrr = np.zeros((rest, rest))
            for i in range(rest):
                for j in range(i, rest):
                    Rrr[i, j] = A[rank + i, rank + j]
            piece = _mm(Rrr.T.copy(), _mm(schur, Rrr))
            for i in range(rest):
                for j in range(rest):
                    Qx[i, j] += 0.5 * (piece[i, j] + piece[j, i])
        else:
            for i in range(size):
                for j in range(size):
                    R_int[node, i, j] = A[rank + i, rank + j] if j >= i else 0.0
                    M_int[node, i, j] = 0.5 * (schur[i, j] + schur[j, i])
    return -1


@numba.njit(cache=True)
def _down_sweep(
    child, h, k, rank, Rzz, Rzx, deferred, carry_pos, S, sigma, Zx, z0, G_all, Y_all, Psi
):  # pragma: no cover - compiled
    """Top-down: ``Phi``/``sigma`` per node and leaf, node solutions and the tree covariance.

    Node ``v``: ``z_v = g_v - G_v s_v - F_v x + y_v xi_v`` in full ``k``
    coordinates (a deferred row reads its carried coordinate, ``z_j =
    x_carried``).  ``Rzx`` columns ``[s (k) | x (n_x) | rhs]``.  Rows ``0..K-1``
    of ``S``/``sigma``/``Psi`` are the leaves, ``K + v`` the internal nodes (a
    node's own shift).  ``Zx[v]``, ``z0[v]`` the node's solution in ``x`` and its
    particular part; ``G_all``/``Y_all`` the node's ``G`` and ``y``; ``Psi`` the
    tree part of ``Cov(s)``.
    """
    n_int = child.shape[0]
    K = S.shape[0] - n_int
    n_x = S.shape[2]
    for node in range(n_int - 1, -1, -1):
        r = rank[node]
        Rinv = np.zeros((r, r))
        for c in range(r):
            for i in range(r - 1, -1, -1):
                s = 1.0 if i == c else 0.0
                for j in range(i + 1, r):
                    s -= Rzz[node, i, j] * Rinv[j, c]
                Rinv[i, c] = s / Rzz[node, i, i]
        elim = np.empty(r, np.int64)
        position = 0
        for j in range(k):
            if not deferred[node, j]:
                elim[position] = j
                position += 1
        G = np.zeros((k, k))
        F = np.zeros((k, n_x))
        g = np.zeros(k)
        Y = np.zeros((k, k))
        for t in range(r):
            row = elim[t]
            for u in range(r):
                Y[row, u] = Rinv[t, u]
            for j in range(k):
                s = 0.0
                for u in range(t, r):
                    s += Rinv[t, u] * Rzx[node, u, j]
                G[row, j] = s
            for e in range(n_x):
                s = 0.0
                for u in range(t, r):
                    s += Rinv[t, u] * Rzx[node, u, k + e]
                F[row, e] = s
            s = 0.0
            for u in range(t, r):
                s += Rinv[t, u] * Rzx[node, u, k + n_x]
            g[row] = s
        for j in range(k):
            if deferred[node, j]:
                F[j, carry_pos[node, j]] = -1.0
        for i in range(k):
            for j in range(k):
                G_all[node, i, j] = G[i, j]
                Y_all[node, i, j] = Y[i, j]
        own = K + node
        for i in range(k):
            for e in range(n_x):
                s = -F[i, e]
                for j in range(k):
                    s -= G[i, j] * S[own, j, e]
                Zx[node, i, e] = s
            s = g[i]
            for j in range(k):
                s -= G[i, j] * sigma[own, j]
            z0[node, i] = s
        for side in range(2):
            c = child[node, side]
            target = -c - 1 if c < 0 else K + c
            factor = h[node, side]
            for i in range(k):
                for e in range(n_x):
                    S[target, i, e] = S[own, i, e] + factor * Zx[node, i, e]
                sigma[target, i] = sigma[own, i] + factor * z0[node, i]
            A = np.eye(k) - factor * G
            AP = _mm(A, Psi[own].copy())
            Psi[target] = _mm(AP, A.T.copy()) + (factor * factor) * _mm(Y, Y.T.copy())


def _leaf_column_norms2(leaf) -> NDArray:
    """Squared column norms ``(K, p - 1)`` of each level's rows over ``[z | intercept | border]``.

    The triangle's column norms are the weighted rows' (Householder QR keeps
    them); signed rows take their error Gram ``sum e_r x_r x_r'``, the
    unsigned scale their rounding is charged at.
    """
    if leaf.signed and leaf.error_diagonal is not None:
        return leaf.error_diagonal.copy()
    top, k = leaf.top, leaf.block_size
    p = top.shape[2]
    a2 = np.sum(top[:, :, : p - 1] ** 2, axis=1)
    a2[:, k:] += leaf.tail_norms2[:, : p - 1 - k]
    return a2


@numba.njit(cache=True)
def _node_column_norms(child, h, level_a2):  # pragma: no cover - compiled
    """Squared node-coordinate column norms ``sum_side h^2 sum_{l in side} a_l^2`` (bottom-up)."""
    n_int = child.shape[0]
    K, k = level_a2.shape
    sub = np.zeros((n_int, k))
    out = np.zeros((n_int, k))
    for node in range(n_int):
        for side in range(2):
            c = child[node, side]
            factor = h[node, side] * h[node, side]
            for j in range(k):
                value = level_a2[-c - 1, j] if c < 0 else sub[c, j]
                out[node, j] += factor * value
                sub[node, j] += value
    return out


# ------------------------------------------------------ inference kernels --
# Every kernel below is a fixed-order recursion over the tree (children before
# parents on the way up, the reverse on the way down), with the node transfer
# A_c = I - h_c G_v of a shift from node v to its child c and the whitened
# innovation map h_c y_v (module docstring).
@numba.njit(cache=True)
def _transfer(G, factor, k):  # pragma: no cover - compiled
    A = np.eye(k)
    for i in range(k):
        for j in range(k):
            A[i, j] -= factor * G[i, j]
    return A


@numba.njit(cache=True)
def _up_vectors(child, h, G_all, Y_all, U_leaf):  # pragma: no cover - compiled
    """Innovation weights ``w_v = sum_c h_c y_v' pi_c`` of level vectors ``U_leaf`` ``(K, k, m)``.

    ``pi_c = sum_{l in sub(c)} P_{l<-c}' u_l`` aggregated upward (``pi_v =
    sum_c A_c' pi_c``): ``w = W' u`` on the innovations.
    """
    n_int = child.shape[0]
    K, k, m = U_leaf.shape
    pi = np.zeros((n_int, k, m))
    w = np.zeros((n_int, k, m))
    for node in range(n_int):
        for side in range(2):
            c = child[node, side]
            source = U_leaf[-c - 1] if c < 0 else pi[c]
            factor = h[node, side]
            A = _transfer(G_all[node], factor, k)
            pi[node] += _mm(A.T.copy(), source)
            w[node] += factor * _mm(Y_all[node].T.copy(), source)
    return w


@numba.njit(cache=True)
def _down_vectors(child, h, G_all, Y_all, w):  # pragma: no cover - compiled
    """Level values ``t_l = sum_{v in anc(l)} T_lv w_v`` of innovation weights ``w`` ``(n_int, k, m)``."""
    n_int, k, m = w.shape
    K = n_int + 1
    t_node = np.zeros((n_int, k, m))
    t_leaf = np.zeros((K, k, m))
    for node in range(n_int - 1, -1, -1):
        own = t_node[node]
        for side in range(2):
            c = child[node, side]
            factor = h[node, side]
            A = _transfer(G_all[node], factor, k)
            value = _mm(A, own) + factor * _mm(Y_all[node], w[node])
            if c < 0:
                t_leaf[-c - 1] = value
            else:
                t_node[c] = value
    return t_leaf, t_node


@numba.njit(cache=True)
def _operator_aggregates(child, h, G_all, Y_all, D_leaf, Xi_leaf):  # pragma: no cover - compiled
    """``Lambda_v = sum_c h_c A_c' Omega_c``, ``X_vv = y_v' (sum_c h_c^2 Omega_c) y_v`` and
    ``X_vx = y_v' sum_c h_c Xi_c`` of a level-space operator.

    ``Omega_c = sum_{l in sub(c)} P' D_l P`` (``Omega_v = sum_d A_d' Omega_d A_d``)
    and ``Xi_c = sum_{l in sub(c)} P' Xi_l`` (``Xi_l = D_l Phi_l + C_l``).
    """
    n_int = child.shape[0]
    K, k, _ = D_leaf.shape
    n = Xi_leaf.shape[2]
    Omega = np.zeros((n_int, k, k))
    Xi = np.zeros((n_int, k, n))
    Lam = np.zeros((n_int, k, k))
    Xvv = np.zeros((n_int, k, k))
    Xvx = np.zeros((n_int, k, n))
    for node in range(n_int):
        theta = np.zeros((k, k))
        xi_sum = np.zeros((k, n))
        for side in range(2):
            c = child[node, side]
            om = D_leaf[-c - 1] if c < 0 else Omega[c]
            xs = Xi_leaf[-c - 1] if c < 0 else Xi[c]
            factor = h[node, side]
            A = _transfer(G_all[node], factor, k)
            At = A.T.copy()
            AtO = _mm(At, om)
            Omega[node] += _mm(AtO, A)
            Xi[node] += _mm(At, xs)
            Lam[node] += factor * AtO
            theta += (factor * factor) * om
            xi_sum += factor * xs
        Yt = Y_all[node].T.copy()
        Xvv[node] = _mm(Yt, _mm(theta, Y_all[node]))
        Xvx[node] = _mm(Yt, xi_sum)
    return Lam, Xvv, Xvx


@numba.njit(cache=True)
def _descendant_sums(child, h, G_all, Y_all, Lam, w):  # pragma: no cover - compiled
    """``sum_{a in desc(v)} X_va w_a = sum_c h_c y_v' mu_c`` with ``mu_v = Lambda_v y_v w_v +
    sum_d A_d' mu_d`` aggregated upward."""
    n_int, k, m = w.shape
    mu = np.zeros((n_int, k, m))
    out = np.zeros((n_int, k, m))
    for node in range(n_int):
        acc = _mm(Lam[node], _mm(Y_all[node], w[node]))
        for side in range(2):
            c = child[node, side]
            if c < 0:
                continue
            factor = h[node, side]
            A = _transfer(G_all[node], factor, k)
            acc += _mm(A.T.copy(), mu[c])
            out[node] += factor * _mm(Y_all[node].T.copy(), mu[c])
        mu[node] = acc
    return out


@numba.njit(cache=True)
def _path_quadratics(child, h, G_all, Y_all, Psi_node, Lam, Xvv, Xvx):  # pragma: no cover
    """At every level, ``Q_l = sum_{a, b in anc(l)} T_lb X_ba T_la'`` and ``rho_l = sum_b T_lb X_bx``.

    ``Q_c = A Q_v A' + h^2 y X_vv y' + h (A Psi_v Lambda_v y y' + transpose)`` and
    ``rho_c = A rho_v + h y X_vx`` from the root (``Q = rho = 0``) down.
    """
    n_int, k, n = Xvx.shape
    K = n_int + 1
    Q_node = np.zeros((n_int, k, k))
    r_node = np.zeros((n_int, k, n))
    Q_leaf = np.zeros((K, k, k))
    r_leaf = np.zeros((K, k, n))
    for node in range(n_int - 1, -1, -1):
        Y = Y_all[node]
        Yt = Y.T.copy()
        PLy = _mm(Psi_node[node], _mm(Lam[node], Y))
        yXy = _mm(Y, _mm(Xvv[node], Yt))
        yX = _mm(Y, Xvx[node])
        for side in range(2):
            c = child[node, side]
            factor = h[node, side]
            A = _transfer(G_all[node], factor, k)
            At = A.T.copy()
            cross = _mm(_mm(A, PLy), Yt)
            Q = _mm(_mm(A, Q_node[node]), At) + (factor * factor) * yXy + factor * (cross + cross.T)
            r = _mm(A, r_node[node]) + factor * yX
            if c < 0:
                Q_leaf[-c - 1] = Q
                r_leaf[-c - 1] = r
            else:
                Q_node[c] = Q
                r_node[c] = r
    return Q_leaf, r_leaf


@numba.njit(cache=True)
def _leaf_path_row_forms(
    levels, B, leaf_parent, leaf_side, node_parent, node_side, h, Rzz, Rzx, rank, deferred, out
):  # pragma: no cover - compiled
    """``sum_{v in anc(l)} ||T_lv' b||^2`` per row of level ``levels[r]`` with piece ``B[r]``.

    Up the row's path, as ``_up_vectors`` for one leaf vector: entering node
    ``v`` from side ``s``, the innovation weight is ``h_vs y_v' u = h_vs
    R_zz,v^-T u_e`` (``u_e`` the eliminated coordinates of ``u``; forward
    substitution on ``R_zz'`` in a fixed order), then ``u <- A' u = u - h_vs
    R_zs,v' R_zz,v^-T u_e``.  The weights' squares add with no cancellation.
    A row with ``levels[r] < 0`` has no level part.
    """
    m, k = B.shape
    u = np.empty(k)
    v = np.empty(k)
    for r in range(m):
        total = 0.0
        level = levels[r]
        if level >= 0:
            for i in range(k):
                u[i] = B[r, i]
            node = leaf_parent[level]
            side = leaf_side[level]
            while node >= 0:
                factor = h[node, side]
                t = 0
                for j in range(k):
                    if deferred[node, j]:
                        continue
                    s = u[j]
                    for a in range(t):
                        s -= Rzz[node, a, t] * v[a]
                    v[t] = s / Rzz[node, t, t]
                    total += (factor * v[t]) * (factor * v[t])
                    t += 1
                for j in range(k):
                    s = 0.0
                    for a in range(rank[node]):
                        s += Rzx[node, a, j] * v[a]
                    u[j] -= factor * s
                side = node_side[node]
                node = node_parent[node]
        out[r] = total


