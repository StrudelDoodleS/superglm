@pytest.mark.parametrize("name", [d.name for d in (*sf.FAMILIES, sf.G.GAMMA)])
def test_declarations_are_scipys_laws(name: str, built) -> None:
    """Generated log density (with its carrier), log survival and log CDF against scipy in the body."""
    module, derived = built(name)
    weights = (1.0, 0.4, 2.5) if derived.data else (1.0,)
    for cell, weight in itertools.product(sf.CELLS[name], weights):
        law = sf.SCIPY[name](*cell, *(weight,) * len(derived.data))
        y = np.array([law.ppf(p) for p in sf.BODY])
        theta = np.tile(cell, (len(y), 1))
        data = tuple(np.full(len(y), weight) for _ in derived.data)
        (density,), _ = law_jets(module, "density", 0, y, theta, data)
        carrier = np.empty(len(y))
        module.carrier(y, *data, np.ones(len(y)), carrier)
        checks = [(density + carrier, law.logpdf(y))]
        for name_, reference in (("logsf", law.logsf), ("logcdf", law.logcdf)):
            if name_ in derived.laws:
                checks.append((law_jets(module, name_, 0, y, theta, data)[0][0], reference(y)))
        for got, reference in checks:
            np.testing.assert_allclose(got, reference, rtol=1e-9, atol=1e-9)


def _richardson(logpdf, theta, y, step=1e-3):
    """Richardson central differences of ``logpdf(*theta)`` in each natural parameter."""

    def f(shift):
        return float(logpdf(*(t * (1.0 + s) for t, s in zip(theta, shift, strict=True))))

    k = len(theta)
    unit = np.eye(k)
    grad = []
    for i in range(k):
        d = [(f(h * unit[i]) - f(-h * unit[i])) / (2 * h * theta[i]) for h in (step, step / 2)]
        grad.append((4 * d[1] - d[0]) / 3)
    hess = []
    for i, j in itertools.combinations_with_replacement(range(k), 2):

        def second(h):
            if i == j:
                return (f(h * unit[i]) - 2 * f(0 * unit[i]) + f(-h * unit[i])) / (h * theta[i]) ** 2
            corners = [f(h * (a * unit[i] + b * unit[j])) * a * b for a in (1, -1) for b in (1, -1)]
            return sum(corners) / (4 * h * h * theta[i] * theta[j])

        hess.append((4 * second(5 * step) - second(10 * step)) / 3)
    return np.array(grad), np.array(hess)


@pytest.mark.parametrize("name", [d.name for d in (*sf.FAMILIES, sf.G.GAMMA)])
def test_differences_of_scipys_log_density_agree(name: str, built) -> None:
    """The score to 1e-6 and the Hessian to 1e-5 of the row's scale: scipy's own logpdf
    error (up to 1.3e-12 relative at CV 0.02) over the steps' ``h`` and ``h^2``."""
    module, derived = built(name)
    for cell in sf.CELLS[name]:
        law = sf.SCIPY[name]
        y = np.array([law(*cell).ppf(p) for p in sf.BODY])
        theta = np.tile(cell, (len(y), 1))
        data = tuple(np.ones(len(y)) for _ in derived.data)
        jets, _ = law_jets(module, "density", 2, y, theta, data)
        for i, value in enumerate(y):
            grad, hess = _richardson(lambda *t: law(*t).logpdf(value), list(cell), value)
            assert np.max(np.abs(jets[1][i] - grad)) <= 1e-6 * np.max(np.abs(grad)), (cell, i)
            assert np.max(np.abs(jets[2][i] - hess)) <= 1e-5 * np.max(np.abs(hess)), (cell, i)


# ---------------------------------------------------------------- the gamma against GammaLS


def _gamma_rows():
    ratios = np.array([1e-6, 1e-3, 0.2, 0.7, 0.98, 1.0, 1.0 + 2**-40, 1.03, 1.6, 5.0, 40.0, 1e3])
    cvs = np.array([0.02, 0.3, 0.83, 1.2, 5.0])
    weights = np.array([1.0, 0.4, 3.0])
    r, cv, w = (a.ravel() for a in np.meshgrid(ratios, cvs, weights, indexing="ij"))
    mean = np.full(len(r), 2500.0)
    return mean * r, mean, cv, w


@pytest.mark.parametrize("semantics", ["prior", "frequency"])
def test_gamma_declaration_reproduces_gamma_ls_rows(semantics: str) -> None:
    """Orders 0-2 of the generated gamma against ``GammaLS``'s hand-written kernel, row by row.

    Both are measured against the declaration at 60 digits, in ``u`` of the
    row's channel scale (absolute below one for the value).  The generated row
    is held to ``max(8 e_hand, 32)``: an outcome check, whose rigorous
    counterpart is the composed bound above.  Where the CV score or curvature
    crosses zero, both kernels lose to the cancellation, amplifying their
    digammas' rounding.  The hand-written kernel's scipy digamma lifts its
    argument to 10, against 16 in ``polygamma_0123``.  Measured: ``e_gen`` at
    most 6.7 ``e_hand`` where ``e_hand >= 4``, at most 20u where it is below,
    and 198u at worst, against 157u for ``e_hand``; ``|gen - hand|`` at most
    59u (value), 149u (score) and 274u (Hessian).
    """
    mp.mp.dps = 60
    derived = sf.G.derive(sf.G.GAMMA)
    y, mean, cv, w = _gamma_rows()
    if semantics == "frequency":
        w = np.ceil(w)
    hand = evaluate_gamma_rows(y, mean, cv, w, semantics, derivative_order=2)
    ones = np.ones(len(y))
    data, multiplier = ((w,), ones) if semantics == "prior" else ((ones,), w)
    jets, valid = law_jets(
        declared_gamma, "density", 2, y, np.column_stack([mean, cv]), data, multiplier
    )
    assert valid.all()
    expected = (hand.optimizing_log_likelihood[:, None], hand.score, hand.hessian_packed)
    for i in range(len(y)):
        weight = w[i] if semantics == "prior" else 1.0
        oracle = sf.Oracle(
            {derived.y: y[i], **dict(zip(derived.theta, (mean[i], cv[i]))), derived.data[0]: weight}
        )
        for order, channels in enumerate(derived.laws["density"][:3]):
            exact = [oracle.value(e) * multiplier[i] for e in channels]
            scale = max(max(abs(e) for e in exact), 1 if order == 0 else 0)
            got = np.atleast_1d(jets[order][i])

            def error(values, exact=exact, scale=scale):
                worst = max(abs(mp.mpf(float(v)) - e) for v, e in zip(values, exact, strict=True))
                return float(worst / scale) / sf.U

            e_gen, e_hand = error(got), error(expected[order][i])
            assert e_gen <= max(8 * e_hand, 32.0), (i, order, e_gen, e_hand)


def test_gamma_declaration_holds_the_symbolic_oracle_tolerances() -> None:
    """``tests/test_family_derivatives_symbolic.py``'s gamma rows and tolerances, orders 1-4.

    Orders 1-2 from the natural-coordinate kernels.  Orders 3-4 come from
    the log-coordinate kernels, which are ``GammaLS``'s predictor jets under
    its log links.  Each order is held to its row's largest entry.  Composing
    the natural jets through the links instead cancels in the chain rule,
    up to 27.7u at order 3 (the CV axis at CV 3) against a tolerance of 17.6u.
    """
    from superglm.distributional import GammaLS
    from superglm.distributional.kernels._declared import gamma_log
    from tests.test_family_derivatives_symbolic import (
        _DIGITS,
        _LSS_CASES,
        _MARGIN,
        _MEASURED,
        _MEASURED_FOURTH,
        _densities,
        _row_oracles,
        _SymbolicRow,
    )

    links = tuple(spec.default_link for spec in GammaLS().parameters)
    assert {type(link).__name__ for link in links} == {"LogLink"}
    _, rows = _LSS_CASES["gamma"]
    expression, symbols = _densities()["gamma"]
    eta_symbols = sp.symbols("e0:2", real=True)
    worst = [0.0, 0.0, 0.0, 0.0]
    for y_value, theta in rows:
        response = sp.Float(y_value, _DIGITS)
        natural = _SymbolicRow(expression.subs(sp.Symbol("y", real=True), response), symbols)
        first, second, _ = natural.evaluate(theta)
        _, predictor = _row_oracles(
            "gamma", y_value, theta, symbols, eta_symbols, links, fourth=True
        )
        eta = np.log(theta)
        _, _, third = predictor.evaluate(eta)
        fourth = predictor.evaluate_fourth(eta)
        weight = (np.ones(1),)
        natural_jets, _ = law_jets(declared_gamma, "density", 2, [y_value], [theta], weight)
        predictor_jets, _ = law_jets(gamma_log, "density", 4, [y_value], [eta], weight)
        references = {
            1: first,
            2: [second[p] for p in sorted(second)],
            3: [third[t] for t in itertools.combinations_with_replacement(range(2), 3)],
            4: [fourth[t] for t in itertools.combinations_with_replacement(range(2), 4)],
        }
        computed = {
            **dict(enumerate(natural_jets[1:], 1)),
            3: predictor_jets[3],
            4: predictor_jets[4],
        }
        for order, reference in references.items():
            scale = max(abs(value) for value in reference)
            error = max(
                abs(mp.mpf(float(c)) - r)
                for c, r in zip(computed[order][0], reference, strict=True)
            )
            worst[order - 1] = max(worst[order - 1], float(error / scale) / sf.U)
    tolerances = [_MARGIN * max(m, 1.0) for m in (*_MEASURED["gamma"], _MEASURED_FOURTH["gamma"])]
    assert all(w <= t for w, t in zip(worst, tolerances, strict=True)), (worst, tolerances)


# ---------------------------------------------------------------- engine primitives


_ENGINE_CELLS = [(0.7, 2.0), (1.5, 0.3), (3.0, 40.0)]
_ENGINE_Y = np.array([0.05, 0.4, 1.0, 2.5, 9.0])


def _engine_rows():
    """Rows of the engine fixture and whether each is inside the lower tail's domain ``u > v``."""
    y = np.tile(_ENGINE_Y, len(_ENGINE_CELLS))
    theta = np.repeat(np.array(_ENGINE_CELLS), len(_ENGINE_Y), axis=0)
    u, v = theta[:, 0] * np.log(y), np.log(theta[:, 1]) - y / theta[:, 0]
    return y, theta, u > v


def test_engine_partials_compose_like_the_closed_form(built) -> None:
    """A declaration naming an engine and the same law in closed form both meet the oracle, to order 4."""
    mp.mp.dps = 60
    y, theta, inside = _engine_rows()
    assert inside.any() and not inside.all()
    for name in ("engine_law", "closed_law"):
        module, derived = built(name)
        for law in ("logsf", "logcdf"):
            rows = np.ones(len(y), bool) if law == "logsf" else inside
            jets, valid = law_jets(module, law, 4, y[rows], theta[rows])
            assert valid.all()
            for i, (value, cell) in enumerate(zip(y[rows], theta[rows], strict=True)):
                oracle = sf.Oracle(_point(derived, value, cell))
                for k, channels in enumerate(derived.laws[law]):
                    for got, e in zip(np.atleast_1d(jets[k][i]), channels, strict=True):
                        bound = C * sf.U * oracle.scale(e) + FLOOR
                        assert abs(mp.mpf(float(got)) - oracle.value(e)) <= bound, (name, law, k, i)


def test_engine_rows_outside_its_domain_are_invalid(built) -> None:
    engine, _ = built("engine_law")
    y, theta, inside = _engine_rows()
    for order in range(5):
        _, valid = law_jets(engine, "logcdf", order, y, theta)
        np.testing.assert_array_equal(valid, inside)
        assert law_jets(engine, "logsf", order, y, theta)[1].all()


def test_each_tail_kernel_calls_its_engine_once_per_row(built) -> None:
    engine, _ = built("engine_law")
    with open(engine.__file__) as handle:
        kernels = dict(re.findall(r"def (\w+)\(.*?\n(.*?)(?=\n@njit|\Z)", handle.read(), re.S))
    calls = {name: body.count("lse_engine(") for name, body in kernels.items()}
    assert calls == {
        **{f"density_{p}": 0 for p in range(5)},
        **{f"{law}_{p}": 1 for law in ("logsf", "logcdf") for p in range(5)},
        "carrier": 0,
    }


