def _point(derived, y, cell):
    data = {symbol: 1.0 for symbol in derived.data}
    return {derived.y: y, **dict(zip(derived.theta, cell, strict=True)), **data}


def _link_hessian(theta, score, hessian):
    pairs = itertools.combinations_with_replacement(range(len(theta)), 2)
    return [
        theta[i] * theta[j] * hessian[m] + (theta[i] * score[i] if i == j else 0)
        for m, (i, j) in enumerate(pairs)
    ]


def _link_scale(theta, score, hessian, a_score, a_hessian):
    """``A`` of the link-scale Hessian formed in float64 from the score and natural Hessian."""
    out = []
    pairs = itertools.combinations_with_replacement(range(len(theta)), 2)
    for m, (i, j) in enumerate(pairs):
        term = abs(theta[i] * theta[j] * hessian[m])
        scale = abs(theta[i] * theta[j]) * a_hessian[m] + 2 * term
        if i == j:
            scale += abs(theta[i]) * a_score[i] + abs(theta[i] * score[i]) + term
        out.append(scale)
    return out


def _grid(name, built):
    """Every entry of the grid: ``(law, order, cell, label, got, exact, A, S)``, link-scale as order ``"link"``."""
    module, derived = built(name)
    entries = []
    for cell in sf.CELLS[name]:
        points = sf.responses(sf.SCIPY[name](*cell))
        y = np.array([value for _, value in points])
        theta = np.tile(cell, (len(y), 1))
        data = tuple(np.ones(len(y)) for _ in derived.data)
        for law, channels in derived.laws.items():
            kernels = [law_jets(module, law, p, y, theta, data)[0] for p in range(5)]
            rows = []
            for i, (label, value) in enumerate(points):
                oracle = sf.Oracle(_point(derived, value, cell))
                exact = [[oracle.value(e) for e in level] for level in channels]
                scale = [[oracle.scale(e) for e in level] for level in channels]
                theta_mp = [mp.mpf(t) for t in cell]
                exact.append(_link_hessian(theta_mp, exact[1], exact[2]))
                scale.append(_link_scale(theta_mp, exact[1], exact[2], scale[1], scale[2]))
                for jets in kernels:
                    got = [[jets[0][i]], *(list(level[i]) for level in jets[1:])]
                    if len(got) > 2:
                        got += [[]] * (5 - len(got)) + [_link_hessian(list(cell), got[1], got[2])]
                    rows.append((label, got, exact, scale))
            levels = len(exact)
            body = [
                max(
                    (max(abs(e) for e in exact[k]) for lab, _, exact, _ in rows if lab[0] == "p"),
                    default=0,
                )
                for k in range(levels)
            ]
            for label, got, exact, scale in rows:
                for k in range(len(got)):
                    if not got[k]:
                        continue
                    s = max(max(abs(e) for e in exact[k]), body[k] if k else 1)
                    for g, e, a in zip(got[k], exact[k], scale[k], strict=True):
                        entries.append((law, "link" if k == 5 else k, cell, label, g, e, a, s))
    return entries


def _gate(entries, name):
    failures = []
    for law, order, cell, label, got, exact, a, _ in entries:
        if (name, law, order, label) in _UNREPRESENTED:
            continue
        if not (math.isfinite(got) and abs(mp.mpf(float(got)) - exact) <= C * sf.U * a + FLOOR):
            failures.append((law, order, cell, label, got, mp.nstr(exact, 8), mp.nstr(a, 4)))
    return failures


@pytest.mark.parametrize("name", [d.name for d in (*sf.FAMILIES, sf.G.GAMMA)])
def test_declared_jets_are_within_the_composed_error_bound(name: str, built) -> None:
    mp.mp.dps = 60
    entries = _grid(name, built)
    assert _gate(entries, name) == []
    quality = [
        (law, order, label, float(a / s))
        for law, order, _, label, _, _, a, s in entries
        if law != "logcdf" and a > Q * s
    ]
    assert quality == []


def test_a_textbook_gamma_fails_the_quality_check(built) -> None:
    """The direct ``a log a - lgamma(a) + ...`` gamma passes the rounding gate but not ``A <= Q S``."""
    mp.mp.dps = 60
    entries = _grid("naive_gamma", built)
    assert _gate(entries, "naive_gamma") == []
    worst = max(float(a / s) for _, _, _, _, _, _, a, s in entries)
    assert worst > 10 * Q


