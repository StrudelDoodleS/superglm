"""Generated severity kernels against independent references (issue #564, stage 2).

Every declaration (the gamma in ``GammaLS``'s parameters, and the Weibull,
mean-form Weibull, Burr XII, log-logistic and Lomax fixtures) is generated by
``tools/generate_severity_families.py`` and checked at body quantiles
0.001-0.999 and at tail probabilities 1e-12, 1e-30 and 1e-100 against three
references:

1. scipy's ``logpdf``, ``logsf`` and ``logcdf`` in the body: the declaration
   is scipy's law;
2. the declaration's own SymPy derivatives at 60 digits, orders 0-4 of every
   law: the derivation, the printed code and the primitives.  Each entry is
   held to ``|err| <= C u A + 1e-300``, ``A`` the primitives' stage-1 bounds
   composed through the expression (``tests._severity_fixtures.Oracle``),
   and so is the link-scale Hessian a log-link solve forms from the score and
   natural Hessian.  ``C = 2`` covers the analysis's second-order terms.
   ``A`` carries the generated subtraction ``1 - t(1 + r)`` of the log CDFs
   at ``u`` times its prefactor, so it grows like ``|log F|`` on the link
   scale and like ``(log F)^2`` on the natural scale, as issue #564
   describes;
3. Richardson differences of scipy's ``logpdf``, orders 1-2 in the body: the
   derivatives without SymPy.

The log density and log survival are also held to ``A <= Q S`` in exact
arithmetic, where ``S`` is the channel scale: the larger of the row's
largest entry of that order and that law's largest over the parameter
cell's body points.  ``Q = 1,024``.  This is what rejects a textbook
declaration, whose generated code cancels: the direct gamma reaches
``A = 2.6e4 S`` in the tails and ``1.9e5 S`` in the body.  The log CDF is
exempt, because its cancellation is the one the model carries.

Measured on this grid (x86-64 Linux, glibc, AMD EPYC 9645):
- ``err / (u A)`` is at most 0.65, natural and link scale.
- ``A / S`` is at most 623 for the log density and log survival (the
  mean-form Weibull at order 4).
- ``err / (u S)`` is at most 15 outside the log CDF.  The Weibull
  natural-scale log-CDF Hessian reaches 201 (body) and 1.9e5 (tail), the
  values issue #564 reports, and 4.9e11 at order 4 in the 1e-100 left tail.

``_UNREPRESENTED`` lists the entries whose generated evaluation leaves the
float64 range.  There ``r^4`` overflows and ``softplus^4`` underflows,
though their product is moderate, and the kernel returns 0 for the fourth
log-CDF derivative of Burr XII and Lomax at ``F = 1e-100``.  A strict xfail
holds them until a stable primitive removes it.
"""

